func TestImplementationRevalidationBindsActualDeclaration(t *testing.T) {
	text := "package fixture\nfunc Real() {\n println(1)\n}\n"
	files := []domain.ExtractedFile{{Path: "neutral.go", Content: text}}
	for _, variant := range []string{"control", "symbol", "start", "end", "hash", "legacy"} {
		t.Run(variant, func(t *testing.T) {
			report := parser.RankGoImplementations("Real", files, 24)
			if len(report.Hits) != 1 {
				t.Fatalf("fixture index: %+v", report)
			}
			switch variant {
			case "symbol":
				report.Hits[0].Symbol = "Invented"
			case "start":
				report.Hits[0].Line = 1
			case "end":
				report.Hits[0].EndLine = 3
			case "hash":
				report.Hits[0].SHA256 = strings.Repeat("0", 64)
			case "legacy":
				report.Hits[0].Kind = ""
				report.Hits[0].Retrieval = ""
			}
			before, _ := json.Marshal(report)
			got := ValidateImplementationRequirements("Real", report, files)
			valid := variant == "control" || variant == "legacy"
			if valid {
				if len(got.Hits) != 1 {
					t.Fatal("valid declaration lost")
				}
			} else {
				if len(got.Hits) != 0 || got.Status != "partial" || len(got.Issues) == 0 {
					t.Fatalf("false declaration retained: %+v", got)
				}
			}
			sources := 0
			for _, r := range got.Requirements {
				sources += len(r.Sources)
			}
			// Legacy retrieval fields stay legible, without fabricating a lexical channel.
			if (variant == "control" && sources != 1) || (!valid && sources != 0) {
				t.Fatal("false requirement source", got.Requirements)
			}
			after, _ := json.Marshal(report)
			if string(before) != string(after) {
				t.Fatal("caller report mutated")
			}
		})
	}
}
func TestImplementationDeclarationKindsAndUnsupportedInputs(t *testing.T) {
	content := "package fixture\ntype Alpha struct{}\ntype Beta struct{}\nfunc (Alpha) Shared() {}\nfunc (Beta) Shared() {}\ntype Queue = Alpha\nvar First, Second = 1, 2\nconst Limit = 3\n"
	files := []domain.ExtractedFile{{Path: "definitions.go", Content: content}}
	for _, query := range []string{"Shared", "Queue", "First", "Second", "Limit"} {
		report := parser.RankGoImplementations(query, files, 24)
		if len(report.Hits) == 0 {
			t.Fatal("missing index control", query)
		}
		got := ValidateImplementationHits(report, files)
		if len(got.Hits) != len(report.Hits) {
			t.Fatalf("declarations lost %s: before=%d after=%d", query, len(report.Hits), len(got.Hits))
		}
	}
	for _, tc := range []struct{ name, path, text string }{{"generated", "neutral.go", "// Code generated by fixture. DO NOT EDIT.\npackage fixture\nfunc Real() {}\n"}, {"invalid", "neutral.go", "package fixture\nfunc Real( {}\n"}, {"language", "neutral.txt", "package fixture\nfunc Real() {}\n"}} {
		t.Run(tc.name, func(t *testing.T) {
			line := strings.Count(tc.text[:strings.Index(tc.text, "func Real")], "\n") + 1
			h := fmt.Sprintf("%x", sha256.Sum256([]byte(tc.text)))
			report := domain.ImplementationSearchReport{Status: "complete", Hits: []domain.ImplementationHit{{Retrieval: "lexical", Kind: "definition", Path: tc.path, Symbol: "Real", Line: line, EndLine: line, SHA256: h, MatchedTerms: []string{"real"}}}}
			got := ValidateImplementationRequirements("Real", report, []domain.ExtractedFile{{Path: tc.path, Content: tc.text}})
			if len(got.Hits) != 0 || got.Status != "partial" {
				t.Fatal("unsupported declaration accepted", got)
			}
		})
	}
}
