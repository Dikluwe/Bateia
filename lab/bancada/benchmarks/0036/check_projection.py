#!/usr/bin/env python3
"""Acceptance assertions for the real Coin projection; Coin is a corpus only.
Run with Markdown and JSON (plain or gzip) paths generated by the CLI.
"""
import gzip
import hashlib
import json
import pathlib
import sys

markdown = pathlib.Path(sys.argv[1]).read_text()
path = pathlib.Path(sys.argv[2])
raw = gzip.decompress(path.read_bytes()) if path.suffix == '.gz' else path.read_bytes()
report = json.loads(raw)
repo = report['results'][0]
evidence = repo['query_evidence']
expected = {
    'handleTransparency', 'doSortedLayersBlendRendering', 'renderOneBlendLayer',
    'initSortedLayersBlendRendering', 'renderSortedLayersFP', 'renderSortedLayersNV',
}
assert expected <= {e['symbol']['name'] for e in evidence['definitions']}
for name in expected:
    assert name in markdown, name
for target in ('initSortedLayersBlendRendering', 'renderOneBlendLayer', 'renderSortedLayersFP', 'renderSortedLayersNV'):
    assert f'doSortedLayersBlendRendering → {target}' in markdown, target
assert any(f['path'] == 'src/actions/SoGLRenderAction.cpp' for f in repo['files'])
assert not any('/XML/' in f['path'] for f in repo['files'])
assert repo['semantic']['status'] == 'partial'
assert repo['semantic']['selected_units'] < repo['semantic']['total_units']
assert report['similarity_results'][0]['overall_score'] == -1
assert report['similarity_results'][0]['evaluation_status'] == 'insufficient'
assert repo['health_score'] == -1
assert 'Não verificado' in markdown
assert 'Order System' not in markdown
assert 'Soluções Exatas Encontradas' not in markdown
assert len(markdown.encode()) < 65000
root = repo['candidate']['url'].removeprefix('file://').rstrip('/')
files = {root + '/' + f['path']: f['content'] for f in repo['files']}
for e in evidence['definitions']:
    content = files[e['symbol']['file']]
    assert hashlib.sha256(content.encode()).hexdigest() == e['sha256']
    lines = content.split('\n')
    assert '\n'.join(lines[e['snippet_first_line']-1:e['snippet_last_line']]) == e['snippet']
print(json.dumps({'markdown_bytes':len(markdown.encode()), 'source_files':len(repo['files']),
 'definitions':len(evidence['definitions']), 'calls':len(evidence['calls']),
 'selected_units':repo['semantic']['selected_units'], 'total_units':repo['semantic']['total_units'],
 'six_central_definitions':True,'status':'passed'},indent=2))
