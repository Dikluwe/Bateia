const doc0051Query = "locate violet lantern"
const doc0051Source = "package sample\n\n// Step locates violet lantern.\n// This is an author claim only.\nfunc Step() int { return 7 }\n"

func doc0051File(path, content string) domain.ExtractedFile {
	return domain.ExtractedFile{Path: path, Content: content, Size: int64(len(content))}
}
func doc0051Hash(s string) string { h := sha256.Sum256([]byte(s)); return hex.EncodeToString(h[:]) }
func doc0051Rank(content string, limit int) domain.ImplementationSearchReport {
	return parser.RankGoImplementations(doc0051Query, []domain.ExtractedFile{doc0051File("sample.go", content)}, limit)
}
func doc0051Docs(r domain.ImplementationSearchReport) []domain.ImplementationHit {
	var out []domain.ImplementationHit
	for _, h := range r.Hits {
		if h.Retrieval == "documentation" {
			out = append(out, h)
		}
	}
	return out
}

func TestDocumentation0051AttachedSource(t *testing.T) {
	r := doc0051Rank(doc0051Source, 10)
	hs := doc0051Docs(r)
	if len(hs) != 1 {
		t.Fatalf("expected one attached Doc hit: %+v", r)
	}
	h := hs[0]
	if h.Symbol != "Step" || h.Kind != "definition" || h.Line != 5 || h.EndLine != 5 || h.DocumentationLine != 3 || h.DocumentationEndLine != 4 || h.SHA256 != doc0051Hash(doc0051Source) {
		t.Fatalf("wrong provenance: %+v", h)
	}
	if h.Score != len(h.MatchedTerms) || h.Score > 99 || len(h.TermWeights) != 0 || !strings.Contains(strings.ToLower(h.Reason), "doc") {
		t.Fatalf("documentary score or reason: %+v", h)
	}
	raw, _ := json.Marshal(h)
	for _, key := range []string{`"documentation_line":3`, `"documentation_end_line":4`, h.SHA256} {
		if !strings.Contains(string(raw), key) {
			t.Errorf("JSON missing %q: %s", key, raw)
		}
	}
}

func TestDocumentation0051ExcludedScopes(t *testing.T) {
	cases := map[string]string{
		"package":    "// violet lantern\npackage sample\nfunc Step() {}\n",
		"loose":      "package sample\n// violet lantern\n\nfunc Step() {}\n",
		"body":       "package sample\nfunc Step() {\n// violet lantern\n}\n",
		"literal":    "package sample\nfunc Step() string { return \"violet lantern\" }\n",
		"type":       "package sample\n// violet lantern\ntype Step struct{}\n",
		"generated":  "// Code generated by fixture. DO NOT EDIT.\npackage sample\n// violet lantern\nfunc Step() {}\n",
		"incomplete": "package sample\n// violet lantern\nfunc Step() {\n",
	}
	for name, src := range cases {
		t.Run(name, func(t *testing.T) {
			if hs := doc0051Docs(doc0051Rank(src, 10)); len(hs) != 0 {
				t.Fatalf("ineligible source: %+v", hs)
			}
		})
	}
}

func TestDocumentation0051MethodAndNegativeClaim(t *testing.T) {
	src := "package sample\ntype Box struct{}\n// Apply does not locate violet lantern.\nfunc (Box) Apply() {}\n"
	r := doc0051Rank(src, 10)
	if len(doc0051Docs(r)) != 1 {
		t.Fatalf("negative wording remains documentation: %+v", r)
	}
	r = usecase.ValidateImplementationRequirements(doc0051Query, r, []domain.ExtractedFile{doc0051File("sample.go", src)})
	if len(r.Requirements) == 0 || r.Requirements[0].Status != "documentation_located" || len(r.Requirements[0].Sources) != 0 || len(r.Requirements[0].DocumentationSources) != 1 {
		t.Fatalf("claim promoted or lost: %+v", r.Requirements)
	}
}

func TestDocumentation0051CodeOrderExactAndDedup(t *testing.T) {
	base := "package sample\nfunc VioletLantern() { helper() }\nfunc helper() {}\n"
	withDoc := strings.Replace(base, "func VioletLantern", "// violet lantern\nfunc VioletLantern", 1)
	// Inserting blank lines first holds declaration locations fixed across variants.
	plain := strings.Replace(base, "func VioletLantern", "\nfunc VioletLantern", 1)
	a := doc0051Rank(plain, 10)
	b := doc0051Rank(withDoc, 10)
	if !reflect.DeepEqual(a.Hits, b.Hits) { // SHA256 is expected to reflect changed bytes.
		for i := range a.Hits {
			a.Hits[i].SHA256 = ""
			for j := range a.Hits[i].RelatedTo {
				a.Hits[i].RelatedTo[j].SHA256 = ""
			}
		}
		for i := range b.Hits {
			b.Hits[i].SHA256 = ""
			for j := range b.Hits[i].RelatedTo {
				b.Hits[i].RelatedTo[j].SHA256 = ""
			}
		}
		if !reflect.DeepEqual(a.Hits, b.Hits) {
			t.Fatalf("Doc changes code order/score or duplicates: before=%+v after=%+v", a.Hits, b.Hits)
		}
	}
	exact := parser.RankGoImplementations("VioletLantern", []domain.ExtractedFile{doc0051File("sample.go", withDoc)}, 10)
	if len(exact.Hits) == 0 || exact.Hits[0].Symbol != "VioletLantern" || len(doc0051Docs(exact)) != 0 {
		t.Fatalf("exact symbol regressed: %+v", exact)
	}
}

func TestDocumentation0051RemainingSlotsAndTie(t *testing.T) {
	files := []domain.ExtractedFile{doc0051File("z.go", doc0051Source), doc0051File("a.go", doc0051Source), doc0051File("code.go", "package sample\nfunc VioletLantern() {}\n")}
	r := parser.RankGoImplementations(doc0051Query, files, 2)
	if len(r.Hits) != 2 || r.Hits[0].Retrieval == "documentation" || r.Hits[1].Path != "a.go" || r.Hits[1].Retrieval != "documentation" || !r.Limited || r.Status != "partial" {
		t.Fatalf("code priority/documentary tie/budget: %+v", r)
	}
}

func TestDocumentation0051ProjectionAndTampering(t *testing.T) {
	files := []domain.ExtractedFile{doc0051File("sample.go", doc0051Source)}
	original := doc0051Rank(doc0051Source, 10)
	valid := usecase.ValidateImplementationRequirements(doc0051Query, original, files)
	if len(valid.Requirements) != 1 {
		t.Fatalf("missing projection: %+v", valid)
	}
	req := valid.Requirements[0]
	if req.Status != "documentation_located" || len(req.Sources) != 0 || len(req.DocumentationSources) != 1 || len(req.MatchedTerms) == 0 || !strings.Contains(strings.ToLower(req.Reason), "doc") {
		t.Fatalf("channels not distinguished: %+v", req)
	}
	raw, _ := json.Marshal(req)
	if !strings.Contains(string(raw), `"documentation_sources"`) {
		t.Fatalf("projection JSON: %s", raw)
	}
	for _, kind := range []string{"hash", "arbitrary_doc", "subset_doc", "symbol", "declaration"} {
		t.Run(kind, func(t *testing.T) {
			r := doc0051Rank(doc0051Source, 10)
			if len(r.Hits) == 0 {
				t.Fatal("no baseline hit")
			}
			switch kind {
			case "hash":
				r.Hits[0].SHA256 = strings.Repeat("0", 64)
			case "arbitrary_doc":
				r.Hits[0].DocumentationLine = 1
				r.Hits[0].DocumentationEndLine = 1
			case "subset_doc":
				r.Hits[0].DocumentationEndLine = 3
			case "symbol":
				r.Hits[0].Symbol = "Else"
			case "declaration":
				r.Hits[0].Line = 4
			}
			checked := usecase.ValidateImplementationHits(r, files)
			if len(checked.Hits) != 0 {
				t.Errorf("forged hit survived: %+v", checked.Hits)
			}
			projected := usecase.ValidateImplementationRequirements(doc0051Query, r, files)
			for _, q := range projected.Requirements {
				if q.Status != "not_verified" || len(q.Sources)+len(q.DocumentationSources) != 0 {
					t.Errorf("forged source survived projection: %+v", q)
				}
			}
		})
	}
	changed := []domain.ExtractedFile{doc0051File("sample.go", strings.Replace(doc0051Source, "return 7", "return 8", 1))}
	if r := usecase.ValidateImplementationHits(original, changed); len(r.Hits) != 0 {
		t.Fatalf("changed reread survived: %+v", r)
	}
	mixedFiles := append(files, doc0051File("code.go", "package sample\nfunc VioletLantern() {}\n"))
	mixed := usecase.ValidateImplementationRequirements(doc0051Query, parser.RankGoImplementations(doc0051Query, mixedFiles, 10), mixedFiles)
	if len(mixed.Requirements) != 1 || mixed.Requirements[0].Status != "evidence_located" || len(mixed.Requirements[0].Sources) == 0 || len(mixed.Requirements[0].DocumentationSources) == 0 {
		t.Fatalf("mixed channels: %+v", mixed.Requirements)
	}
}
